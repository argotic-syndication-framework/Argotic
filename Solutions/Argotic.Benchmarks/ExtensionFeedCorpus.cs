using System.Globalization;
using System.Text;

namespace Argotic.Benchmarks;

/// <summary>
/// Builds the extension-focused benchmark inputs: the modern podcast feed, the
/// declared-but-unused production shape, and the deliberately-maximal every-family document.
/// </summary>
/// <remarks>
/// <para>
/// <see cref="FeedCorpus.GenerateRssWithExtensionsUtf8"/> emits six families' simplest elements,
/// and that single choice left nine families and every rich element mix without a benchmark
/// (<c>.endjin/build-warnings.md</c> §19). The three generators here close that from opposite
/// directions: census-ratio realism for the family 62% of live feeds declare, the ~96% production
/// shape in which namespaces are declared but never used, and a ceiling document that exercises
/// every collection-bearing element the extension families model.
/// </para>
/// <para>
/// Element mixes cite their sources: the committed <c>SampleData/PodcastFeed.xml</c> and the
/// per-element census in <c>.endjin/build-warnings.md</c> §2.50 (podcast), the 627-feed
/// declared-vs-used census in the corpus manifest (declared-only), and the scenario-test fixtures
/// (YouTube's <c>media:group</c>, the FeedSync spec example, the LiveJournal userpic) for the
/// maximal arm.
/// </para>
/// <para>
/// Reading the raw string literals: every block ends with a blank line, and that final empty line
/// is what encodes the trailing newline after the block's last content line. The generated bytes
/// are pinned by a hash sweep across every shape-cycle count.
/// </para>
/// </remarks>
internal static class ExtensionFeedCorpus
{
    /// <summary>
    /// Generates a Podcasting 2.0 feed with iTunes at genuine podcast density.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    /// <para>
    ///     Channel elements follow §2.50's adoption order (locked, guid, medium, podping, txt,
    ///     funding, person); the per-item <c>podcast:transcript</c> cycles the three MIME types
    ///     that dominate the 396-feed validation — <c>text/vtt</c>, <c>text/plain</c> and the
    ///     unregistered <c>application/srt</c> — because a corpus that only emits the registered
    ///     types would flatter any type-keyed handling. <c>podcast:license</c> carries a
    ///     copyright-notice value rather than an SPDX identifier, which is what publishers
    ///     actually put there. The namespace is the https:// form, matched exactly: a feed
    ///     declaring http:// silently yields no extension at all, which is precisely the drift
    ///     the consuming benchmark's guard exists to catch.
    /// </para>
    /// <para>
    ///     iTunes rides along at The Daily's measured density (23,525 elements over 2,939 items —
    ///     roughly eight per item plus the channel set), including the nested
    ///     <c>itunes:category</c> and <c>itunes:owner</c> that light the two element classes
    ///     nothing else reaches.
    /// </para>
    /// </remarks>
    public static byte[] GeneratePodcastFeedUtf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 2048 + (itemCount * 1536));

        builder.Append("""
            <?xml version="1.0" encoding="utf-8"?>
            <rss version="2.0"
                 xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd"
                 xmlns:podcast="https://podcastindex.org/namespace/1.0"
                 xmlns:content="http://purl.org/rss/1.0/modules/content/"
                 xmlns:media="http://search.yahoo.com/mrss/">
              <channel>
                <title>Synthetic Podcast Feed</title>
                <link>https://example.com/podcast</link>
                <description>A synthetic Podcasting 2.0 feed at census-ratio element density.</description>
                <language>en-us</language>
                <podcast:locked owner="owner@example.com">yes</podcast:locked>
                <podcast:guid>917393e3-1b1e-5cef-ace4-edaa54e1f810</podcast:guid>
                <podcast:medium>podcast</podcast:medium>
                <podcast:podping usesPodping="true"/>
                <podcast:txt purpose="applepodcastsverify">e6cfaae0-9496-11f0-a272-f9e230f88be0</podcast:txt>
                <podcast:funding url="https://example.com/support">Support the show</podcast:funding>
                <podcast:person role="host" href="https://example.com/hosts/alice">Alice Host</podcast:person>
                <podcast:person role="guest" href="https://example.com/guests/bob">Bob Guest</podcast:person>
                <itunes:author>Example Productions</itunes:author>
                <itunes:category text="Technology">
                  <itunes:category text="Tech News"/>
                </itunes:category>
                <itunes:owner>
                  <itunes:name>Example Productions</itunes:name>
                  <itunes:email>owner@example.com</itunes:email>
                </itunes:owner>
                <itunes:type>episodic</itunes:type>
                <itunes:new-feed-url>https://example.com/podcast/feed.xml</itunes:new-feed-url>
                <itunes:explicit>false</itunes:explicit>
                <itunes:image href="https://example.com/artwork.png"/>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            string transcriptType = (i % 3) switch
            {
                0 => "text/vtt",
                1 => "text/plain",
                _ => "application/srt",
            };

            builder.Append(CultureInfo.InvariantCulture, $"""
                    <item>
                      <title>Episode {ordinal}</title>
                      <link>https://example.com/podcast/episode{ordinal}</link>
                      <description>Show notes for episode {ordinal}.</description>
                      <guid isPermaLink="false">episode-{ordinal}</guid>
                      <pubDate>Mon, 01 Jan 2024 10:00:00 GMT</pubDate>
                      <enclosure url="https://example.com/media/episode{ordinal}.mp3" length="36588921" type="audio/mpeg"/>
                      <podcast:season name="Season One">1</podcast:season>

                """);

            builder.Append(i % 4 == 3
                ? $"""
                        <podcast:episode display="Bonus">{ordinal}.1</podcast:episode>

                  """
                : $"""
                        <podcast:episode display="Ep. {ordinal}">{ordinal}</podcast:episode>

                  """);

            builder.Append(CultureInfo.InvariantCulture, $"""
                      <podcast:transcript url="https://example.com/podcast/episode{ordinal}/transcript" type="{transcriptType}" language="en" rel="captions"/>
                      <podcast:person role="host" href="https://example.com/hosts/alice">Alice Host</podcast:person>

                """);

            if (i % 8 == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <podcast:chapters url="https://example.com/podcast/episode{ordinal}/chapters.json" type="application/json+chapters"/>

                    """);
            }

            if (i % 16 == 0)
            {
                // The value publishers actually write: a copyright notice, not an SPDX identifier.
                builder.Append("""
                          <podcast:license url="https://example.com/license">Copyright 2026 Example Productions</podcast:license>

                    """);
            }

            builder.Append(CultureInfo.InvariantCulture, $"""
                      <itunes:title>Episode {ordinal}</itunes:title>
                      <itunes:episodeType>full</itunes:episodeType>
                      <itunes:duration>00:42:{(i % 60).ToString("D2", CultureInfo.InvariantCulture)}</itunes:duration>
                      <itunes:explicit>false</itunes:explicit>
                      <itunes:author>Example Productions</itunes:author>
                      <itunes:subtitle>A short teaser for episode {ordinal}</itunes:subtitle>
                      <itunes:summary>A longer summary of what episode {ordinal} covers.</itunes:summary>
                      <itunes:image href="https://example.com/artwork/episode{ordinal}.png"/>
                      <content:encoded><![CDATA[<p>Full show notes for episode {ordinal} with <a href="https://example.com">links</a>.</p>]]></content:encoded>
                      <media:thumbnail url="https://example.com/thumbs/episode{ordinal}.jpg"/>
                    </item>

                """);
        }

        builder.Append("""
              </channel>
            </rss>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates the shape most production loads actually take: nine extension namespaces
    /// declared, five families used.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    ///     The 627-feed census: <c>dc</c> declared by 404 and used by 382, <c>content</c> 401/321,
    ///     <c>sy</c> 296/293, <c>wfw</c> 306/225, <c>slash</c> 298/225 — and <c>geo</c>
    ///     <b>121/5</b>, <c>georss</c> <b>144/4</b>, <c>creativeCommons</c> 28/1. WordPress
    ///     stamps the declarations into every response whether or not a plugin ever writes an
    ///     element, and detection answers on the prefix alone, so the unused declarations force
    ///     extension loads that find nothing on every entity. This generator emits exactly that:
    ///     the five used families' everyday elements, and not one element of the other four.
    /// </remarks>
    public static byte[] GenerateDeclaredOnlyProductionUtf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 1536 + (itemCount * 640));

        builder.Append("""
            <?xml version="1.0" encoding="utf-8"?>
            <rss version="2.0"
                 xmlns:dc="http://purl.org/dc/elements/1.1/"
                 xmlns:content="http://purl.org/rss/1.0/modules/content/"
                 xmlns:sy="http://purl.org/rss/1.0/modules/syndication/"
                 xmlns:slash="http://purl.org/rss/1.0/modules/slash/"
                 xmlns:wfw="http://wellformedweb.org/CommentAPI/"
                 xmlns:media="http://search.yahoo.com/mrss/"
                 xmlns:geo="http://www.w3.org/2003/01/geo/wgs84_pos#"
                 xmlns:georss="http://www.georss.org/georss"
                 xmlns:creativeCommons="http://backend.userland.com/creativeCommonsRssModule">
              <channel>
                <title>Production Weblog</title>
                <link>https://example.com/blog</link>
                <description>A synthetic feed in the WordPress declared-but-unused shape.</description>
                <language>en-us</language>
                <sy:updatePeriod>hourly</sy:updatePeriod>
                <sy:updateFrequency>1</sy:updateFrequency>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            builder.Append(CultureInfo.InvariantCulture, $"""
                    <item>
                      <title>Post {ordinal}</title>
                      <link>https://example.com/blog/post{ordinal}</link>
                      <description>Excerpt of post {ordinal}.</description>
                      <pubDate>Mon, 01 Jan 2024 10:00:00 GMT</pubDate>
                      <guid isPermaLink="true">https://example.com/blog/post{ordinal}</guid>
                      <dc:creator>Blog Author</dc:creator>
                      <content:encoded><![CDATA[<p>The full body of post {ordinal} with <strong>markup</strong>.</p>]]></content:encoded>
                      <wfw:commentRss>https://example.com/blog/post{ordinal}/comments/feed</wfw:commentRss>
                      <slash:comments>7</slash:comments>
                    </item>

                """);
        }

        builder.Append("""
              </channel>
            </rss>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates the ceiling document: every framework family the RSS surface can carry, with
    /// every collection-bearing element populated.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    /// <para>
    ///     Deliberately a fiction — no real feed looks like this, and no number measured over it
    ///     may be quoted as production-relevant. It exists so that every extension element class
    ///     has a price at all. Three honesty labels carried over from the corpus manifest:
    ///     FeedSync, SimpleList and FeedRank exist in the wild only as their spec examples, so
    ///     those are the shapes emitted; LiveJournal is emitted under Argotic's 2.0 namespace URI
    ///     because real LiveJournal feeds use the 1.0 URI this library does not match — the arm
    ///     prices code paths, not live traffic; and <c>media:group</c> is the YouTube shape, the
    ///     only real publisher of the element.
    /// </para>
    /// <para>
    ///     Podcasting 2.0 is deliberately absent: it has its own census-ratio generator, and a
    ///     second copy here would price the same paths twice.
    /// </para>
    /// </remarks>
    public static byte[] GenerateMaximalExtensionFeedUtf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 4096 + (itemCount * 2560));

        builder.Append("""
            <?xml version="1.0" encoding="utf-8"?>
            <rss version="2.0"
                 xmlns:dc="http://purl.org/dc/elements/1.1/"
                 xmlns:dcterms="http://purl.org/dc/terms/"
                 xmlns:content="http://purl.org/rss/1.0/modules/content/"
                 xmlns:slash="http://purl.org/rss/1.0/modules/slash/"
                 xmlns:sy="http://purl.org/rss/1.0/modules/syndication/"
                 xmlns:geo="http://www.w3.org/2003/01/geo/wgs84_pos#"
                 xmlns:georss="http://www.georss.org/georss"
                 xmlns:blogChannel="http://backend.userland.com/blogChannelModule"
                 xmlns:creativeCommons="http://backend.userland.com/creativeCommonsRssModule"
                 xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd"
                 xmlns:media="http://search.yahoo.com/mrss/"
                 xmlns:wfw="http://wellformedweb.org/CommentAPI/"
                 xmlns:trackback="http://madskills.com/public/xml/rss/module/trackback/"
                 xmlns:pingback="http://madskills.com/public/xml/rss/module/pingback/"
                 xmlns:lj="http://livejournal.org/rss/lj/2.0/"
                 xmlns:sx="http://feedsync.org/2007/feedsync"
                 xmlns:cf="http://www.microsoft.com/schemas/rss/core/2005"
                 xmlns:fh="http://purl.org/syndication/history/1.0"
                 xmlns:re="http://purl.org/atompub/rank/1.0"
                 xmlns:photo="http://www.pheed.com/pheed/"
                 xmlns:atom="http://www.w3.org/2005/Atom">
              <channel>
                <title>Maximal Extension Feed</title>
                <link>https://example.com/</link>
                <description>The ceiling document: every family, every collection-bearing element.</description>
                <language>en-us</language>
                <sy:updatePeriod>hourly</sy:updatePeriod>
                <sy:updateFrequency>1</sy:updateFrequency>
                <sy:updateBase>2024-01-01T00:00:00Z</sy:updateBase>
                <blogChannel:blogRoll>https://example.com/blogroll.opml</blogChannel:blogRoll>
                <blogChannel:blink>https://example.com/recommended</blogChannel:blink>
                <creativeCommons:license>https://creativecommons.org/licenses/by/4.0/</creativeCommons:license>
                <fh:archive/>
                <atom:link rel="current" href="https://example.com/feed.xml"/>
                <atom:link rel="prev-archive" href="https://example.com/archive/2023-12.xml"/>
                <cf:treatAs>list</cf:treatAs>
                <cf:listinfo>
                  <cf:sort ns="" element="pubDate" label="Date" data-type="date" default="true"/>
                  <cf:sort ns="http://purl.org/dc/elements/1.1/" element="creator" label="Author" data-type="text"/>
                  <cf:group ns="" element="category" label="Category"/>
                </cf:listinfo>
                <sx:sharing since="2024-01-01T00:00:00Z" until="2024-02-01T00:00:00Z">
                  <sx:related link="https://example.com/feed-complete.xml" type="complete"/>
                </sx:sharing>
                <itunes:author>Example Productions</itunes:author>
                <itunes:category text="Technology">
                  <itunes:category text="Tech News"/>
                </itunes:category>
                <itunes:owner>
                  <itunes:name>Example Productions</itunes:name>
                  <itunes:email>owner@example.com</itunes:email>
                </itunes:owner>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            AppendMaximalItem(builder, i);
        }

        builder.Append("""
              </channel>
            </rss>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    private static void AppendMaximalItem(StringBuilder builder, int index)
    {
        string ordinal = index.ToString(CultureInfo.InvariantCulture);

        // The everyday families ride on every item; the once-per-document showcases follow below.
        builder.Append(CultureInfo.InvariantCulture, $"""
                <item>
                  <title>Maximal Article {ordinal}</title>
                  <link>https://example.com/article{ordinal}</link>
                  <description>Body text for maximal article {ordinal}.</description>
                  <pubDate>Mon, 01 Jan 2024 10:00:00 GMT</pubDate>
                  <guid isPermaLink="true">https://example.com/article{ordinal}</guid>
                  <dc:creator>Article Author {ordinal}</dc:creator>
                  <dc:subject>technology</dc:subject>
                  <dc:date>2024-01-01T10:00:00Z</dc:date>
                  <dcterms:abstract>An abstract of article {ordinal}</dcterms:abstract>
                  <dcterms:modified>2024-01-02T10:00:00Z</dcterms:modified>
                  <content:encoded><![CDATA[<p>Full content of article {ordinal}.</p>]]></content:encoded>
                  <slash:section>articles</slash:section>
                  <slash:department>benchmarking</slash:department>
                  <slash:comments>42</slash:comments>
                  <slash:hit_parade>42,30,20,10,5,2,1</slash:hit_parade>
                  <wfw:comment>https://example.com/article{ordinal}/comment</wfw:comment>
                  <wfw:commentRss>https://example.com/article{ordinal}/comments/feed</wfw:commentRss>
                  <trackback:ping>https://example.com/article{ordinal}/trackback</trackback:ping>
                  <trackback:about>https://example.com/article{ordinal}/trackbacks</trackback:about>
                  <pingback:server>https://example.com/pingback</pingback:server>
                  <pingback:target>https://example.com/article{ordinal}</pingback:target>
                  <geo:lat>51.5074</geo:lat>
                  <geo:long>-0.1278</geo:long>
                  <georss:point>51.5074 -0.1278</georss:point>
                  <re:rank scheme="http://example.com/rank-scheme" domain="https://example.com/">{ordinal}</re:rank>
                  <photo:thumbnail>https://example.com/photo/thumb{ordinal}.jpg</photo:thumbnail>
                  <photo:imgsrc>https://example.com/photo/full{ordinal}.jpg</photo:imgsrc>
                  <lj:security>public</lj:security>
                  <lj:mood>productive</lj:mood>
                  <lj:music>Around the World</lj:music>
                  <lj:userpic><url>https://example.com/userpic.jpg</url><keyword>coding</keyword><width>100</width><height>100</height></lj:userpic>
                  <media:thumbnail url="https://example.com/thumb{ordinal}.jpg"/>
                  <sx:sync id="article-{ordinal}" updates="3">
                    <sx:history sequence="3" when="2024-01-03T10:00:00Z" by="editor"/>
                    <sx:history sequence="2" when="2024-01-02T10:00:00Z" by="author"/>
                    <sx:history sequence="1" when="2024-01-01T10:00:00Z" by="author"/>
                  </sx:sync>

            """);

        // The geometry showcase, once per document: the GeoRSS shapes beyond a point.
        if (index == 0)
        {
            builder.Append("""
                      <georss:line>45.256 -110.45 46.46 -109.48 43.84 -109.86</georss:line>
                      <georss:polygon>45.256 -110.45 46.46 -109.48 43.84 -109.86 45.256 -110.45</georss:polygon>
                      <georss:box>42.943 -71.032 43.039 -69.856</georss:box>
                      <georss:featurename>Example Valley</georss:featurename>
                      <georss:elev>313</georss:elev>

                """);
        }

        // The Yahoo Media long tail, once per document - the census finds each of these "once or
        // twice across all eight" real documents.
        if (index == 1)
        {
            builder.Append("""
                      <media:hash algo="md5">dfdec888b72151965a34b4b59e290372</media:hash>
                      <media:player url="https://example.com/player?article=1" height="390" width="640"/>
                      <media:category scheme="http://search.yahoo.com/mrss/category_schema">technology/benchmarks</media:category>
                      <media:copyright url="https://example.com/copyright">2026 Example Corporation</media:copyright>
                      <media:credit role="author" scheme="urn:ebu">Alice Author</media:credit>
                      <media:rating scheme="urn:simple">nonadult</media:rating>
                      <media:restriction relationship="allow" type="country">gb us</media:restriction>
                      <media:text type="plain">A caption for the media object.</media:text>

                """);
        }

        // The YouTube media:group shape, once per document - the only real publisher of the element.
        if (index == 2)
        {
            builder.Append("""
                      <media:group>
                        <media:title>A Video</media:title>
                        <media:content url="https://example.com/v/abc" type="video/mp4" width="640" height="390"/>
                        <media:content url="https://example.com/v/abc-hd" type="video/mp4" width="1280" height="720"/>
                        <media:content url="https://example.com/a/abc" type="audio/mp4"/>
                        <media:thumbnail url="https://example.com/vi/abc/hqdefault.jpg" width="480" height="360"/>
                        <media:description>A description of the video.</media:description>
                      </media:group>

                """);
        }

        builder.Append("""
                </item>

            """);
    }
