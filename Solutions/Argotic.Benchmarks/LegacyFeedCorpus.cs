using System.Globalization;
using System.Text;

namespace Argotic.Benchmarks;

/// <summary>
/// Builds the legacy-format benchmark inputs: the RSS versions before 2.0, Atom 0.3 and RSD 0.6.
/// </summary>
/// <remarks>
/// <para>
/// These formats had zero benchmark coverage while their adapters total 1,520 lines
/// (<c>.endjin/build-warnings.md</c> §19) — every load benchmark parsed RSS 2.0 or Atom 1.0, so
/// the version-dispatch cost and the RDF-shaped parse had no price at all. Element mixes are
/// modelled on the test fixtures in <c>FeedTestData.cs</c> (which the benchmarks project cannot
/// reference) and on the real 1999–2005 documents in the gitignored perf-spike corpus: BBC's RSS
/// 0.91 ships ISO-8859-1 with a DOCTYPE, Slashdot's RSS 0.90 carries no version attribute and is
/// recognised by namespace alone, and RSS 1.0 aggregators grow an <c>rdf:Seq</c> manifest in
/// lockstep with their items.
/// </para>
/// <para>
/// Deliberately absent: a <c>version="0.94"</c> generator, even though one real feed shipped that
/// string. The dispatch supports 2.0, 1.0, 0.92, 0.91 and 0.9 and throws for anything else, so
/// the arm would measure an exception rather than a load, and a parse-verify guard on it could
/// never pass.
/// </para>
/// <para>
/// Reading the raw string literals: every block ends with a blank line, and that final empty line
/// is what encodes the trailing newline after the block's last content line — a raw literal's
/// closing delimiter otherwise swallows it. The generated bytes are pinned by a hash sweep across
/// every shape-cycle count, so an accidental whitespace change here fails loudly rather than
/// silently shifting the committed benchmark baselines.
/// </para>
/// </remarks>
internal static class LegacyFeedCorpus
{
    /// <summary>
    /// Generates an RSS 0.90 document: RDF root, Netscape namespace, and no version attribute —
    /// the format is recognised by namespace sniffing alone.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    public static byte[] GenerateRss090Utf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 768 + (itemCount * 128));

        builder.Append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"
                     xmlns="http://my.netscape.com/rdf/simple/0.9/">
              <channel>
                <title>Legacy Benchmark Feed 0.90</title>
                <link>http://example.com</link>
                <description>A synthetic RSS 0.90 feed in the Netscape My.Netscape.Com shape.</description>
              </channel>
              <image>
                <title>Feed Image</title>
                <url>http://example.com/image.png</url>
                <link>http://example.com</link>
              </image>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            builder.Append(CultureInfo.InvariantCulture, $"""
                  <item>
                    <title>Headline {ordinal}</title>
                    <link>http://example.com/item{ordinal}</link>
                  </item>

                """);
        }

        builder.Append("""
              <textinput>
                <title>Search</title>
                <description>Search the feed</description>
                <name>query</name>
                <link>http://example.com/search</link>
              </textinput>
            </rdf:RDF>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates a full RSS 0.91 document: rating, skipHours/skipDays, textInput and a
    /// width/height image — the complete optional-element surface of the format.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    public static byte[] GenerateRss091Utf8(int itemCount)
        => Encoding.UTF8.GetBytes(BuildRss091Document(itemCount, withDoctype: false, latin1Accents: false));

    /// <summary>
    /// Generates the same RSS 0.91 document as it actually travelled in 1999: ISO-8859-1 bytes, a
    /// PUBLIC Netscape DOCTYPE, and Latin-1 accented characters in the text.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as ISO-8859-1 bytes.</returns>
    /// <remarks>
    ///     The corpus's real 0.91 feeds (BBC, Wired, xml.com) are ISO-8859-1 and carry SYSTEM or
    ///     PUBLIC DOCTYPEs; a UTF-8-only corpus can never reach the encoding-detection and
    ///     DTD-handling paths those documents exercise on every load.
    /// </remarks>
    public static byte[] GenerateRss091Iso88591WithDoctype(int itemCount)
        => Encoding.GetEncoding("ISO-8859-1").GetBytes(BuildRss091Document(itemCount, withDoctype: true, latin1Accents: true));

    /// <summary>
    /// Generates a full RSS 0.92 document: everything 0.91 carried plus <c>cloud</c>, and per-item
    /// <c>enclosure</c>/<c>category</c>/<c>source</c> cycling the way real items vary.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    public static byte[] GenerateRss092Utf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 1536 + (itemCount * 384));

        builder.Append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <rss version="0.92">
              <channel>
                <title>Legacy Benchmark Feed 0.92</title>
                <link>http://example.com</link>
                <description>A synthetic RSS 0.92 feed with the cloud and enclosure surface.</description>
                <language>en-us</language>
                <copyright>Copyright 2026 Example Corporation</copyright>
                <managingEditor>editor@example.com</managingEditor>
                <webMaster>webmaster@example.com</webMaster>
                <pubDate>Mon, 01 Jan 2024 08:00:00 GMT</pubDate>
                <lastBuildDate>Mon, 01 Jan 2024 12:00:00 GMT</lastBuildDate>
                <cloud domain="rpc.example.com" port="80" path="/RPC2" registerProcedure="pingMe" protocol="soap"/>
                <image>
                  <title>Feed Image</title>
                  <url>http://example.com/image.png</url>
                  <link>http://example.com</link>
                  <width>88</width>
                  <height>31</height>
                </image>
                <skipHours>
                  <hour>1</hour>
                  <hour>2</hour>
                </skipHours>
                <skipDays>
                  <day>Saturday</day>
                  <day>Sunday</day>
                </skipDays>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            int shape = i % 3;
            string ordinal = i.ToString(CultureInfo.InvariantCulture);

            builder.Append(CultureInfo.InvariantCulture, $"""
                    <item>
                      <title>Article {ordinal}</title>
                      <link>http://example.com/item{ordinal}</link>
                      <description>Body text for article {ordinal}.</description>

                """);

            if (shape == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <enclosure url="http://example.com/media/episode{ordinal}.mp3" length="12345678" type="audio/mpeg"/>

                    """);
            }

            builder.Append("""
                      <category>Technology</category>

                """);

            if (shape != 2)
            {
                builder.Append("""
                          <category domain="http://example.com/categories">News</category>

                    """);
            }

            if (shape == 1)
            {
                builder.Append("""
                          <source url="http://other.example.com/feed.xml">Other Feed</source>

                    """);
            }

            builder.Append("""
                    </item>

                """);
        }

        builder.Append("""
              </channel>
            </rss>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates an RSS 1.0 (RDF) document whose <c>rdf:Seq</c> manifest grows with the item
    /// count, with Dublin Core at its native RSS 1.0 density and the slash quartet on one item in
    /// ten — the Slashdot shape.
    /// </summary>
    /// <param name="itemCount">The number of <c>item</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    ///     The RDF bookkeeping is the point: every item is listed twice (once as an
    ///     <c>rdf:li</c> in the channel manifest, once as the item itself), which is the parse
    ///     shape no RSS 2.0 corpus can price. Dublin Core rides along because RSS 1.0 is its
    ///     native habitat — the corpus's aggregated RDF feeds carry <c>dc:</c> on every item.
    /// </remarks>
    public static byte[] GenerateRss10Utf8(int itemCount)
    {
        StringBuilder builder = new(capacity: 1536 + (itemCount * 512));

        builder.Append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"
                     xmlns="http://purl.org/rss/1.0/"
                     xmlns:dc="http://purl.org/dc/elements/1.1/"
                     xmlns:content="http://purl.org/rss/1.0/modules/content/"
                     xmlns:slash="http://purl.org/rss/1.0/modules/slash/">
              <channel rdf:about="http://example.com">
                <title>Legacy Benchmark Feed 1.0</title>
                <link>http://example.com</link>
                <description>A synthetic RSS 1.0 feed in the aggregated RDF shape.</description>
                <dc:publisher>Example Corporation</dc:publisher>
                <items>
                  <rdf:Seq>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            builder.Append(CultureInfo.InvariantCulture, $"""
                        <rdf:li resource="http://example.com/item{i.ToString(CultureInfo.InvariantCulture)}"/>

                """);
        }

        builder.Append("""
                  </rdf:Seq>
                </items>
              </channel>
              <image rdf:about="http://example.com/image.png">
                <title>Feed Image</title>
                <url>http://example.com/image.png</url>
                <link>http://example.com</link>
              </image>

            """);

        for (int i = 0; i < itemCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);

            builder.Append(CultureInfo.InvariantCulture, $"""
                  <item rdf:about="http://example.com/item{ordinal}">
                    <title>Aggregated Article {ordinal}</title>
                    <link>http://example.com/item{ordinal}</link>
                    <description>Body text for aggregated article {ordinal}.</description>
                    <dc:creator>Author {ordinal}</dc:creator>
                    <dc:creator>Second Author</dc:creator>
                    <dc:date>2024-01-01T10:00:00Z</dc:date>
                    <dc:identifier>http://example.com/item{ordinal}</dc:identifier>
                    <dc:source>http://origin.example.com/feed</dc:source>
                    <content:encoded><![CDATA[<p>Full content of aggregated article {ordinal}.</p>]]></content:encoded>

                """);

            if (i % 10 == 0)
            {
                builder.Append("""
                        <slash:section>articles</slash:section>
                        <slash:department>benchmarking</slash:department>
                        <slash:comments>42</slash:comments>
                        <slash:hit_parade>42,30,20,10,5,2,1</slash:hit_parade>

                    """);
            }

            builder.Append("""
                  </item>

                """);
        }

        builder.Append("""
            </rdf:RDF>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates an Atom 0.3 document: the <c>modified</c>/<c>created</c>/<c>issued</c> date
    /// triple, <c>tagline</c>, and entries alternating escaped HTML content with inline XHTML —
    /// the two content modes real 0.3 publishers used.
    /// </summary>
    /// <param name="entryCount">The number of <c>entry</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    public static byte[] GenerateAtom03Utf8(int entryCount)
    {
        StringBuilder builder = new(capacity: 1024 + (entryCount * 512));

        builder.Append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <feed version="0.3" xmlns="http://purl.org/atom/ns#" xmlns:xhtml="http://www.w3.org/1999/xhtml">
              <title mode="escaped">Legacy Benchmark Feed (Atom 0.3)</title>
              <id>urn:uuid:60a76c80-d399-11d9-b93C-0003939e0af6</id>
              <modified>2024-01-01T12:00:00Z</modified>
              <link rel="alternate" type="text/html" href="http://example.com"/>
              <tagline>A synthetic Atom 0.3 feed in the Blogger-era shape.</tagline>
              <copyright>Copyright 2026 Example Corporation</copyright>
              <generator url="http://example.com/generator" version="1.0">Argotic Benchmarks</generator>
              <author>
                <name>Feed Author</name>
                <url>http://example.com/author</url>
                <email>author@example.com</email>
              </author>
              <contributor>
                <name>Feed Contributor</name>
              </contributor>

            """);

        for (int i = 0; i < entryCount; i++)
        {
            int shape = i % 3;
            string ordinal = i.ToString(CultureInfo.InvariantCulture);

            builder.Append(CultureInfo.InvariantCulture, $"""
                  <entry>
                    <title mode="escaped">Entry {ordinal}</title>
                    <id>urn:uuid:entry-{ordinal}</id>
                    <modified>2024-01-01T10:00:00Z</modified>
                    <created>2023-12-31T10:00:00Z</created>
                    <issued>2024-01-01T09:00:00Z</issued>
                    <link rel="alternate" type="text/html" href="http://example.com/entry{ordinal}"/>

                """);

            if (shape != 2)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                        <author>
                          <name>Entry Author {ordinal}</name>
                        </author>

                    """);
            }

            builder.Append(CultureInfo.InvariantCulture, $"""
                    <summary mode="escaped">Summary for entry {ordinal}.</summary>

                """);

            builder.Append(shape == 1
                ? """
                      <content type="text/html" mode="xml">
                        <xhtml:div>Entry content in <xhtml:strong>XHTML</xhtml:strong>.</xhtml:div>
                      </content>

                  """
                : $"""
                      <content type="text/html" mode="escaped">&lt;p&gt;Escaped HTML content for entry {ordinal}.&lt;/p&gt;</content>

                  """);

            builder.Append("""
                  </entry>

                """);
        }

        builder.Append("""
            </feed>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates an RSD 0.6 document with the requested number of APIs, cycling the engines a
    /// real discovery document lists and carrying <c>settings</c> on every fourth API.
    /// </summary>
    /// <param name="apiCount">The number of <c>api</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    public static byte[] GenerateRsd06Utf8(int apiCount)
    {
        StringBuilder builder = new(capacity: 512 + (apiCount * 224));

        builder.Append("""
            <?xml version="1.0" encoding="UTF-8"?>
            <rsd version="0.6" xmlns="http://archipelago.phrasewise.com/rsd">
              <service>
                <engineName>Example Blog Engine</engineName>
                <engineLink>http://example.com/engine</engineLink>
                <homePageLink>http://example.com</homePageLink>
                <apis>

            """);

        for (int i = 0; i < apiCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            string name = (i % 3) switch
            {
                0 => "MetaWeblog",
                1 => "Blogger",
                _ => "WordPress",
            };
            string preferred = i == 0 ? "true" : "false";

            if (i % 4 == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <api name="{name}" preferred="{preferred}" apiLink="http://example.com/xmlrpc{ordinal}" blogID="{ordinal}">
                            <settings>
                              <setting name="docs">http://www.xmlrpc.com/metaWeblogApi</setting>
                              <setting name="notes">Synthetic API entry {ordinal}</setting>
                            </settings>
                          </api>

                    """);
            }
            else
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <api name="{name}" preferred="{preferred}" apiLink="http://example.com/xmlrpc{ordinal}" blogID="{ordinal}"/>

                    """);
            }
        }

        builder.Append("""
                </apis>
              </service>
            </rsd>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    private static string BuildRss091Document(int itemCount, bool withDoctype, bool latin1Accents)
    {
        // The accented strings stay within Latin-1 so the ISO-8859-1 arm round-trips its encoding
        // rather than silently substituting.
        string editor = latin1Accents ? "rédacteur@example.com (René Éditeur)" : "editor@example.com";
        string titleSuffix = latin1Accents ? " — édition française" : string.Empty;
        string language = latin1Accents ? "fr" : "en-us";
        string encoding = latin1Accents ? "iso-8859-1" : "UTF-8";

        StringBuilder builder = new(capacity: 1536 + (itemCount * 256));

        builder.Append(CultureInfo.InvariantCulture, $"""
            <?xml version="1.0" encoding="{encoding}"?>

            """);

        if (withDoctype)
        {
            builder.Append("""
                <!DOCTYPE rss PUBLIC "-//Netscape Communications//DTD RSS 0.91//EN"
                  "http://my.netscape.com/publish/formats/rss-0.91.dtd">

                """);
        }

        builder.Append(CultureInfo.InvariantCulture, $"""
            <rss version="0.91">
              <channel>
                <title>Legacy Benchmark Feed 0.91{titleSuffix}</title>
                <link>http://example.com</link>
                <description>A synthetic RSS 0.91 feed with the full optional-element surface.</description>
                <language>{language}</language>
                <copyright>Copyright 2026 Example Corporation</copyright>
                <managingEditor>{editor}</managingEditor>
                <webMaster>webmaster@example.com</webMaster>
                <rating>(PICS-1.1 "http://www.classify.org/safesurf/" 1 r (SS~~000 1))</rating>
                <pubDate>Mon, 01 Jan 2024 08:00:00 GMT</pubDate>
                <lastBuildDate>Mon, 01 Jan 2024 12:00:00 GMT</lastBuildDate>
                <image>
                  <title>Feed Image</title>
                  <url>http://example.com/image.png</url>
                  <link>http://example.com</link>
                  <width>88</width>
                  <height>31</height>
                  <description>Logo for the feed</description>
                </image>
                <textInput>
                  <title>Search</title>
                  <description>Search the feed</description>
                  <name>query</name>
                  <link>http://example.com/search</link>
                </textInput>
                <skipHours>
                  <hour>1</hour>
                  <hour>2</hour>
                </skipHours>
                <skipDays>
                  <day>Saturday</day>
                  <day>Sunday</day>
                </skipDays>

            """);

        string itemTitle = latin1Accents ? "Dépêche " : "Bulletin ";
        string itemBody = latin1Accents ? "Résumé de la dépêche " : "Body text for bulletin ";

        for (int i = 0; i < itemCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            builder.Append(CultureInfo.InvariantCulture, $"""
                    <item>
                      <title>{itemTitle}{ordinal}</title>
                      <link>http://example.com/item{ordinal}</link>
                      <description>{itemBody}{ordinal}.</description>
                    </item>

                """);
        }

        builder.Append("""
              </channel>
            </rss>

            """);

        return builder.ToString();
    }
