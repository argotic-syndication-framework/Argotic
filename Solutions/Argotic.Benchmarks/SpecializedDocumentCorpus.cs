using System.Globalization;
using System.Text;

namespace Argotic.Benchmarks;

/// <summary>
/// Builds the specialized-document benchmark inputs: BlogML exports and APML attention profiles
/// at controllable scale.
/// </summary>
/// <remarks>
/// <para>
/// The committed samples are small (a 4-post BlogML export, a 3-profile APML document), so
/// cost-versus-size for these formats did not exist — §19 names the 1,000-post blog export as the
/// realistic missing scenario, because BlogML is an engine-to-engine migration format and a real
/// export is as large as the blog it moves. Shapes are modelled on the committed
/// <c>BlogMLDocument.xml</c> and <c>ApmlDocument.xml</c>, including the deliberate approval-status
/// mix the sample's own comment explains: "approved" is exactly the field an importer must not
/// get wrong, because getting it wrong publishes something the author did not.
/// </para>
/// <para>
/// Every sixteenth post carries an <i>embedded</i> base64 attachment (~1 KB) rather than the
/// sample's linked one — embedded attachments are where a migration document's decode cost
/// lives, and a corpus without one leaves that path priced at zero.
/// </para>
/// <para>
/// Reading the raw string literals: every block ends with a blank line, and that final empty line
/// is what encodes the trailing newline after the block's last content line. The generated bytes
/// are pinned by a hash sweep across every shape-cycle count.
/// </para>
/// </remarks>
internal static class SpecializedDocumentCorpus
{
    private const string EmbeddedPayloadSeed = "iVBORw0KGgoAAAANSUhEUgAAAAgAAAAICAYAAADED76LAAAAJUlEQVR4nGP8//8/AzGAiSitUYWjCkcVjiocVUg1hQAAAP//AwB4";

    /// <summary>
    /// Generates a BlogML 2.0 export with the requested number of posts.
    /// </summary>
    /// <param name="postCount">The number of <c>post</c> elements to emit.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    ///     Three authors (one unapproved), a category hierarchy with <c>parentref</c>, and per
    ///     post: HTML content, two category refs, two comments (plus an unapproved third on every
    ///     fourth post), a trackback on every eighth, and an embedded base64 attachment on every
    ///     sixteenth.
    /// </remarks>
    public static byte[] GenerateBlogMLUtf8(int postCount)
    {
        string embeddedPayload = string.Concat(Enumerable.Repeat(EmbeddedPayloadSeed, 10));

        StringBuilder builder = new(capacity: 2048 + (postCount * 1280));

        builder.Append("""
            <?xml version="1.0" encoding="utf-8"?>
            <blog root-url="https://example.com/blog/" date-created="2026-01-05T08:00:00Z" xmlns="http://www.blogml.com/2006/09/BlogML">
              <title type="text">Synthetic Export</title>
              <sub-title type="html">&lt;em&gt;Synthetic&lt;/em&gt; blog export at scale</sub-title>
              <authors>
                <author id="author-1" date-created="2026-01-05T08:00:00Z" date-modified="2026-08-07T12:00:00Z" approved="true" email="alice@example.com">
                  <title type="text">Alice Author</title>
                </author>
                <author id="author-2" date-created="2026-01-05T08:00:00Z" date-modified="2026-08-06T10:00:00Z" approved="true" email="bob@example.com">
                  <title type="text">Bob Blogger</title>
                </author>
                <author id="author-3" date-created="2026-01-05T08:00:00Z" date-modified="2026-07-29T09:00:00Z" approved="false" email="carol@example.com">
                  <title type="text">Carol Contributor</title>
                </author>
              </authors>
              <extended-properties>
                <property name="CommentModeration" value="true"/>
                <property name="BlogEngine" value="synthetic"/>
              </extended-properties>
              <categories>
                <category id="cat-1" date-created="2026-01-05T08:00:00Z" date-modified="2026-08-07T12:00:00Z" approved="true" parentref="0">
                  <title type="text">Engineering</title>
                </category>
                <category id="cat-2" date-created="2026-01-05T08:00:00Z" date-modified="2026-08-05T11:00:00Z" approved="true" parentref="cat-1">
                  <title type="text">Benchmarks</title>
                </category>
                <category id="cat-3" date-created="2026-01-05T08:00:00Z" date-modified="2026-08-06T10:00:00Z" approved="true" parentref="cat-1">
                  <title type="text">Syndication</title>
                </category>
              </categories>
              <posts>

            """);

        for (int i = 0; i < postCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            string views = ((i * 13) % 5000).ToString(CultureInfo.InvariantCulture);
            string authorRef = ((i % 3) + 1).ToString(CultureInfo.InvariantCulture);
            string categoryRef = ((i % 2) + 2).ToString(CultureInfo.InvariantCulture);

            builder.Append(CultureInfo.InvariantCulture, $"""
                    <post id="post-{ordinal}" date-created="2026-08-07T10:00:00Z" date-modified="2026-08-07T12:00:00Z" approved="true" post-url="https://example.com/blog/post{ordinal}" type="normal" hasexcerpt="true" views="{views}">
                      <title type="text">Post {ordinal}</title>
                      <excerpt type="html">&lt;p&gt;Excerpt of post {ordinal}.&lt;/p&gt;</excerpt>
                      <content type="html">&lt;p&gt;The full body of post {ordinal}, long enough to carry the markup a real post carries: &lt;strong&gt;emphasis&lt;/strong&gt;, a &lt;a href="https://example.com"&gt;link&lt;/a&gt;, and a list.&lt;/p&gt;&lt;ul&gt;&lt;li&gt;one&lt;/li&gt;&lt;li&gt;two&lt;/li&gt;&lt;/ul&gt;</content>
                      <post-name type="text">post-{ordinal}</post-name>
                      <authors>
                        <author ref="author-{authorRef}"/>
                      </authors>
                      <categories>
                        <category ref="cat-1"/>
                        <category ref="cat-{categoryRef}"/>
                      </categories>
                      <comments>
                        <comment id="comment-{ordinal}-1" date-created="2026-08-07T11:00:00Z" date-modified="2026-08-07T11:00:00Z" approved="true" user-name="Reader One" user-email="reader1@example.com">
                          <content type="text">A comment on post {ordinal}.</content>
                        </comment>
                        <comment id="comment-{ordinal}-2" date-created="2026-08-07T11:30:00Z" date-modified="2026-08-07T11:30:00Z" approved="true" user-name="Reader Two">
                          <content type="text">A second comment on post {ordinal}.</content>
                        </comment>

                """);

            if (i % 4 == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                            <comment id="comment-{ordinal}-3" date-created="2026-08-07T12:00:00Z" date-modified="2026-08-07T12:00:00Z" approved="false" user-name="Unmoderated">
                              <content type="text">An unapproved comment awaiting moderation.</content>
                            </comment>

                    """);
            }

            builder.Append("""
                      </comments>

                """);

            if (i % 8 == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <trackbacks>
                            <trackback id="trackback-{ordinal}" date-created="2026-08-07T11:15:00Z" date-modified="2026-08-07T11:15:00Z" approved="true" url="https://other.example.com/trackback/post{ordinal}">
                              <title type="text">Referenced elsewhere</title>
                            </trackback>
                          </trackbacks>

                    """);
            }

            if (i % 16 == 0)
            {
                builder.Append(CultureInfo.InvariantCulture, $"""
                          <attachments>
                            <attachment id="attach-{ordinal}" date-created="2026-08-07T10:00:00Z" date-modified="2026-08-07T10:00:00Z" approved="true" url="https://example.com/images/post{ordinal}.png" mime-type="image/png" size="1040" embedded="true" path="images/post{ordinal}.png">{embeddedPayload}</attachment>
                          </attachments>

                    """);
            }

            builder.Append("""
                    </post>

                """);
        }

        builder.Append("""
              </posts>
            </blog>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }

    /// <summary>
    /// Generates an APML 0.6 attention profile with the requested number of implicit concepts.
    /// </summary>
    /// <param name="conceptCount">The number of implicit <c>Concept</c> elements in the first profile.</param>
    /// <returns>The generated document as UTF-8 bytes.</returns>
    /// <remarks>
    ///     Two profiles with a <c>defaultprofile</c> selection (the attribute only means something
    ///     when there is a choice), implicit and explicit data sub-trees, sources at a quarter of
    ///     the concept count each carrying an <c>Author</c>, and an <c>Applications</c> block —
    ///     the committed sample's proportions, scaled.
    /// </remarks>
    public static byte[] GenerateApmlUtf8(int conceptCount)
    {
        int sourceCount = Math.Max(1, conceptCount / 4);
        int explicitCount = Math.Max(1, conceptCount / 4);

        StringBuilder builder = new(capacity: 1024 + (conceptCount * 192));

        builder.Append("""
            <?xml version="1.0" encoding="utf-8"?>
            <APML xmlns="http://www.apml.org/apml-0.6" version="0.6">
              <Head>
                <Title>Synthetic attention profile</Title>
                <Generator>Argotic Benchmarks</Generator>
                <UserEmail>user@example.com</UserEmail>
                <DateCreated>2026-01-05T08:00:00Z</DateCreated>
              </Head>
              <Body defaultprofile="primary">
                <Profile name="primary">
                  <ImplicitData>
                    <Concepts>

            """);

        for (int i = 0; i < conceptCount; i++)
        {
            string value = (0.5 + ((i % 50) / 100.0)).ToString("F2", CultureInfo.InvariantCulture);
            builder.Append(CultureInfo.InvariantCulture, $"""
                          <Concept key="topic-{i.ToString(CultureInfo.InvariantCulture)}" value="{value}" from="https://example.com/observed" updated="2026-08-07T12:00:00Z"/>

                """);
        }

        builder.Append("""
                    </Concepts>
                    <Sources>

            """);

        for (int i = 0; i < sourceCount; i++)
        {
            string ordinal = i.ToString(CultureInfo.InvariantCulture);
            builder.Append(CultureInfo.InvariantCulture, $"""
                          <Source key="https://example.com/feeds/{ordinal}" value="0.90" name="Feed {ordinal}" type="application/rss+xml" from="https://example.com" updated="2026-08-07T12:00:00Z">
                            <Author key="author-{ordinal}" value="0.85" from="https://example.com" updated="2026-08-07T12:00:00Z"/>
                          </Source>

                """);
        }

        builder.Append("""
                    </Sources>
                  </ImplicitData>
                  <ExplicitData>
                    <Concepts>

            """);

        for (int i = 0; i < explicitCount; i++)
        {
            builder.Append(CultureInfo.InvariantCulture, $"""
                          <Concept key="stated-topic-{i.ToString(CultureInfo.InvariantCulture)}" value="1.0"/>

                """);
        }

        builder.Append("""
                    </Concepts>
                  </ExplicitData>
                </Profile>
                <Profile name="secondary">
                  <ImplicitData>
                    <Concepts>
                      <Concept key="weekend-topic" value="0.60" from="https://example.com/observed" updated="2026-08-07T12:00:00Z"/>
                    </Concepts>
                  </ImplicitData>
                </Profile>
                <Applications>
                  <Application name="example-reader">
                    <ReaderSettings theme="dark" refresh="hourly"/>
                  </Application>
                </Applications>
              </Body>
            </APML>

            """);

        return Encoding.UTF8.GetBytes(builder.ToString());
    }
}